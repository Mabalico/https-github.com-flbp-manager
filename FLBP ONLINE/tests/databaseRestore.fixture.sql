create sequence public.restore_delete_probe;
create function public.restore_delete_probe_trigger() returns trigger language plpgsql as $$
begin
  perform nextval('public.restore_delete_probe');
  return old;
end;
$$;
create trigger restore_delete_probe after delete on public.app_settings
  for each row execute function public.restore_delete_probe_trigger();
create function public.restore_insert_failure_trigger() returns trigger language plpgsql as $$
begin
  if current_setting('test.restore_insert_failure', true) = 'on' then
    raise exception 'Injected failure after destructive phase';
  end if;
  return new;
end;
$$;
create trigger restore_insert_failure before insert on public.fanta_rosters
  for each row execute function public.restore_insert_failure_trigger();
