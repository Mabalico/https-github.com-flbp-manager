-- Conferma l'intero batch oppure non conferma nulla. Evita che un
-- on-conflict-ignore faccia sparire dal disco un'operazione che in realtà si è
-- scontrata con un operation_id/versione remota differente.
create or replace function public.flbp_local_append_operations(
  p_workspace_id text,
  p_node_id text,
  p_epoch bigint,
  p_operations jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_workspace_id text := coalesce(nullif(trim(p_workspace_id), ''), 'default');
  v_node_id text := nullif(trim(coalesce(p_node_id, '')), '');
  v_plane record;
  v_cloud record;
  v_cursor bigint := 0;
  v_entry jsonb;
  v_operation_id text;
  v_local_version bigint;
  v_operation_kind text;
  v_payload jsonb;
  v_created_at timestamptz;
  v_existing record;
  v_confirmed integer := 0;
  v_inserted integer := 0;
  v_idempotent integer := 0;
  v_covered integer := 0;
begin
  if auth.role() <> 'service_role' then raise exception 'service_role richiesta'; end if;
  if v_node_id is null then raise exception 'node_id mancante'; end if;
  if coalesce(p_epoch, 0) <= 0 then raise exception 'primary_epoch mancante'; end if;
  if jsonb_typeof(coalesce(p_operations, '[]'::jsonb)) <> 'array' then
    raise exception 'p_operations deve essere un array JSON';
  end if;
  if jsonb_array_length(coalesce(p_operations, '[]'::jsonb)) > 100 then
    raise exception 'Massimo 100 operazioni per batch';
  end if;

  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || v_workspace_id));
  select * into v_plane
  from public.flbp_data_plane
  where workspace_id = v_workspace_id
  for update;
  if not found or v_plane.mode not in ('local', 'recovery')
    or v_plane.node_id <> v_node_id or v_plane.epoch <> p_epoch
  then
    raise exception 'FLBP_EPOCH_FENCED: journal rifiutato, il nodo non possiede più questo epoch';
  end if;

  select version, last_operation_id into v_cloud
  from public.workspace_state
  where workspace_id = v_workspace_id
  for update;
  v_cursor := coalesce(v_cloud.version, 0);
  select greatest(v_cursor, coalesce(max(local_version), v_cursor)) into v_cursor
  from public.flbp_local_operation_log
  where workspace_id = v_workspace_id and primary_epoch = p_epoch;

  for v_entry in
    select value from jsonb_array_elements(coalesce(p_operations, '[]'::jsonb)) with ordinality
    order by ordinality
  loop
    v_operation_id := trim(coalesce(v_entry->>'operation_id', ''));
    v_local_version := coalesce((v_entry->>'local_version')::bigint, 0);
    v_operation_kind := trim(coalesce(v_entry->>'operation_kind', ''));
    v_payload := coalesce(v_entry->'payload', '{}'::jsonb);
    v_created_at := (v_entry->>'created_at')::timestamptz;

    if v_operation_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,199}$' then
      raise exception 'FLBP_INVALID_OPERATION: operation_id non valido';
    end if;
    if v_local_version <= 0 then raise exception 'FLBP_INVALID_OPERATION: local_version non valida'; end if;
    if v_operation_kind not in ('workspace-snapshot', 'match-result') then
      raise exception 'FLBP_INVALID_OPERATION: operation_kind non supportato';
    end if;
    if jsonb_typeof(v_payload) <> 'object' then
      raise exception 'FLBP_INVALID_OPERATION: payload deve essere un oggetto JSON';
    end if;

    select * into v_existing
    from public.flbp_local_operation_log
    where workspace_id = v_workspace_id and operation_id = v_operation_id;
    if found then
      if v_existing.node_id is distinct from v_node_id
        or v_existing.primary_epoch is distinct from p_epoch
        or v_existing.local_version is distinct from v_local_version
        or v_existing.operation_kind is distinct from v_operation_kind
        or v_existing.payload is distinct from v_payload
        or v_existing.created_at is distinct from v_created_at
      then
        raise exception 'FLBP_OPERATION_COLLISION: operation_id % associato a dati differenti', v_operation_id;
      end if;
      v_idempotent := v_idempotent + 1;
      v_confirmed := v_confirmed + 1;
      continue;
    end if;

    -- Un backup completo più recente rende superflui i record precedenti. La
    -- versione esattamente uguale è coperta solo se il suo operation_id è lo
    -- stesso registrato nello snapshot canonico.
    if v_local_version < coalesce(v_cloud.version, 0) then
      v_covered := v_covered + 1;
      v_confirmed := v_confirmed + 1;
      continue;
    end if;
    if v_local_version = coalesce(v_cloud.version, 0) then
      if v_operation_id <> coalesce(v_cloud.last_operation_id, '') then
        raise exception 'FLBP_OPERATION_COLLISION: versione cloud % associata a un’altra operazione', v_local_version;
      end if;
      v_covered := v_covered + 1;
      v_confirmed := v_confirmed + 1;
      continue;
    end if;

    if v_local_version <> v_cursor + 1 then
      raise exception 'FLBP_JOURNAL_GAP: attesa versione %, trovata %', v_cursor + 1, v_local_version;
    end if;

    insert into public.flbp_local_operation_log(
      workspace_id, node_id, primary_epoch, operation_id,
      local_version, operation_kind, payload, created_at
    ) values (
      v_workspace_id, v_node_id, p_epoch, v_operation_id,
      v_local_version, v_operation_kind, v_payload, v_created_at
    );
    v_cursor := v_local_version;
    v_inserted := v_inserted + 1;
    v_confirmed := v_confirmed + 1;
  end loop;

  return jsonb_build_object(
    'ok', true,
    'confirmed', v_confirmed,
    'inserted', v_inserted,
    'idempotent', v_idempotent,
    'covered_by_snapshot', v_covered,
    'high_water_version', v_cursor
  );
end;
$$;

-- Scrittura cloud Admin idempotente. Il nome v2 permette un rollout senza
-- interrompere per qualche minuto i client ancora collegati alla RPC legacy.
-- Una risposta persa può essere ritentata con lo stesso operation_id; se nel
-- frattempo il DB è avanzato, il retry diventa un conflitto e non un overwrite.
create or replace function public.flbp_admin_push_workspace_state_v2(
  p_workspace_id text,
  p_state jsonb,
  p_public_state jsonb,
  p_base_updated_at timestamptz,
  p_force boolean,
  p_lease_holder text,
  p_operation_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_workspace_id text := nullif(trim(coalesce(p_workspace_id, '')), '');
  v_operation_id text := trim(coalesce(p_operation_id, ''));
  v_current public.workspace_state%rowtype;
  v_has_current boolean := false;
  v_current_public_state jsonb;
  v_history record;
  v_next_updated_at timestamptz := clock_timestamp();
  v_next_version bigint;
begin
  if v_workspace_id is null then raise exception 'Workspace non valido'; end if;
  if not public.flbp_is_admin() then raise exception 'Accesso admin richiesto'; end if;
  if v_operation_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,199}$' then
    raise exception 'FLBP_INVALID_OPERATION: operation_id non valido';
  end if;

  perform public.flbp_admin_assert_write_lease(v_workspace_id, p_lease_holder);
  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || v_workspace_id));
  insert into public.workspaces(id) values (v_workspace_id) on conflict (id) do nothing;

  select * into v_current
  from public.workspace_state
  where workspace_id = v_workspace_id
  for update;
  v_has_current := found;
  select state into v_current_public_state
  from public.public_workspace_state
  where workspace_id = v_workspace_id
  for update;

  if v_has_current and v_current.last_operation_id = v_operation_id then
    if v_current.state is distinct from coalesce(p_state, '{}'::jsonb)
      or coalesce(v_current_public_state, '{}'::jsonb) is distinct from coalesce(p_public_state, '{}'::jsonb)
    then
      raise exception 'FLBP_OPERATION_COLLISION: operation_id già associato a dati differenti';
    end if;
    return jsonb_build_object(
      'ok', true, 'idempotent', true,
      'updated_at', v_current.updated_at,
      'version', v_current.version,
      'operation_id', v_operation_id
    );
  end if;

  select version, state into v_history
  from public.workspace_state_versions
  where workspace_id = v_workspace_id and operation_id = v_operation_id
  order by version desc limit 1;
  if found then
    if v_history.state is distinct from coalesce(p_state, '{}'::jsonb) then
      raise exception 'FLBP_OPERATION_COLLISION: operation_id storico associato a dati differenti';
    end if;
    raise exception 'FLBP_DB_CONFLICT: operazione già applicata alla versione %, ora superata dalla versione %',
      v_history.version, v_current.version
      using detail = jsonb_build_object('updated_at', v_current.updated_at, 'version', v_current.version)::text;
  end if;

  if v_has_current and not coalesce(p_force, false) then
    if p_base_updated_at is null then
      raise exception 'FLBP_DB_CONFLICT: il DB contiene già uno snapshot Admin'
        using detail = jsonb_build_object('updated_at', v_current.updated_at, 'version', v_current.version)::text;
    end if;
    if v_current.updated_at is distinct from p_base_updated_at then
      raise exception 'FLBP_DB_CONFLICT: il DB è stato aggiornato da un altro Admin'
        using detail = jsonb_build_object('updated_at', v_current.updated_at, 'version', v_current.version)::text;
    end if;
  end if;

  if v_has_current
    and v_current.state is not distinct from coalesce(p_state, '{}'::jsonb)
    and coalesce(v_current_public_state, '{}'::jsonb) is not distinct from coalesce(p_public_state, '{}'::jsonb)
  then
    return jsonb_build_object(
      'ok', true, 'idempotent', true, 'no_change', true,
      'updated_at', v_current.updated_at,
      'version', v_current.version,
      'operation_id', v_current.last_operation_id
    );
  end if;

  insert into public.workspace_state(
    workspace_id, state, updated_at, version, last_operation_id, primary_epoch
  ) values (
    v_workspace_id, coalesce(p_state, '{}'::jsonb), v_next_updated_at,
    1, v_operation_id, null
  ) on conflict (workspace_id) do update set
    state = excluded.state,
    updated_at = excluded.updated_at,
    last_operation_id = excluded.last_operation_id,
    primary_epoch = null
  returning version into v_next_version;

  insert into public.public_workspace_state(workspace_id, state, updated_at)
  values (v_workspace_id, coalesce(p_public_state, '{}'::jsonb), v_next_updated_at)
  on conflict (workspace_id) do update set state = excluded.state, updated_at = excluded.updated_at;

  perform public.flbp_upsert_public_workspace_live(
    v_workspace_id,
    coalesce(p_public_state, '{}'::jsonb),
    v_next_updated_at
  );

  return jsonb_build_object(
    'ok', true, 'idempotent', false,
    'updated_at', v_next_updated_at,
    'version', v_next_version,
    'operation_id', v_operation_id
  );
end;
$$;

drop function if exists public.flbp_local_activate_data_plane(text, text, text, integer);
create or replace function public.flbp_local_activate_data_plane(
  p_workspace_id text,
  p_node_id text,
  p_base_url text,
  p_expected_cloud_version bigint,
  p_expected_cloud_operation_id text,
  p_expected_cloud_state jsonb,
  p_expected_public_state jsonb,
  p_expected_plane_epoch bigint,
  p_expected_recovered_version bigint,
  p_ttl_seconds integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_workspace_id text := coalesce(nullif(trim(p_workspace_id), ''), 'default');
  v_node_id text := nullif(trim(coalesce(p_node_id, '')), '');
  v_base_url text := nullif(trim(coalesce(p_base_url, '')), '');
  v_ttl integer := least(greatest(coalesce(p_ttl_seconds, 60), 30), 300);
  v_current record;
  v_cloud record;
  v_public_state jsonb;
  v_journal_version bigint;
  v_epoch bigint;
  v_expires timestamptz := now() + make_interval(secs => v_ttl);
begin
  if auth.role() <> 'service_role' then raise exception 'service_role richiesta'; end if;
  if v_node_id is null then raise exception 'node_id mancante'; end if;
  if v_base_url is null or v_base_url !~ '^https://' then raise exception 'base_url HTTPS obbligatorio'; end if;

  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || v_workspace_id));
  insert into public.workspaces(id) values (v_workspace_id) on conflict (id) do nothing;
  select * into v_current from public.flbp_data_plane where workspace_id = v_workspace_id for update;
  if found and v_current.mode = 'local' and v_current.lease_expires_at > now() and v_current.node_id <> v_node_id then
    raise exception 'FLBP_LOCAL_PRIMARY: un altro nodo locale possiede già la leadership';
  end if;
  if coalesce(v_current.epoch, 0) <> coalesce(p_expected_plane_epoch, 0) then
    raise exception 'FLBP_ACTIVATION_CHANGED: epoch coordinatore cambiato durante il download';
  end if;

  select state, version, last_operation_id into v_cloud
  from public.workspace_state
  where workspace_id = v_workspace_id
  for update;
  if not found then
    raise exception 'FLBP_ACTIVATION_CHANGED: snapshot cloud assente';
  end if;
  if v_cloud.version <> coalesce(p_expected_cloud_version, 0)
    or coalesce(v_cloud.last_operation_id, '') <> coalesce(p_expected_cloud_operation_id, '')
    or v_cloud.state is distinct from coalesce(p_expected_cloud_state, '{}'::jsonb)
  then
    raise exception 'FLBP_ACTIVATION_CHANGED: snapshot privato cambiato durante il download';
  end if;

  select state into v_public_state
  from public.public_workspace_state
  where workspace_id = v_workspace_id
  for update;
  if not found then v_public_state := v_cloud.state; end if;
  if v_public_state is distinct from coalesce(p_expected_public_state, '{}'::jsonb) then
    raise exception 'FLBP_ACTIVATION_CHANGED: snapshot pubblico cambiato durante il download';
  end if;

  select max(local_version) into v_journal_version
  from public.flbp_local_operation_log
  where workspace_id = v_workspace_id
    and primary_epoch = coalesce(p_expected_plane_epoch, 0);
  v_journal_version := greatest(v_cloud.version, coalesce(v_journal_version, v_cloud.version));
  if v_journal_version <> coalesce(p_expected_recovered_version, v_cloud.version) then
    raise exception 'FLBP_ACTIVATION_CHANGED: journal locale avanzato durante il download';
  end if;
  v_epoch := coalesce(v_current.epoch, 0) + 1;

  insert into public.flbp_data_plane(workspace_id, mode, node_id, base_url, epoch, lease_expires_at, last_heartbeat_at, updated_at)
  values (v_workspace_id, 'local', v_node_id, v_base_url, v_epoch, v_expires, now(), now())
  on conflict (workspace_id) do update set
    mode = 'local', node_id = excluded.node_id, base_url = excluded.base_url,
    epoch = excluded.epoch, lease_expires_at = excluded.lease_expires_at,
    last_heartbeat_at = excluded.last_heartbeat_at, updated_at = now();

  return jsonb_build_object(
    'ok', true, 'mode', 'local', 'epoch', v_epoch,
    'lease_expires_at', v_expires,
    'cloud_version', v_cloud.version,
    'recovered_version', v_journal_version
  );
end;
$$;

create or replace function public.flbp_local_heartbeat_data_plane(
  p_workspace_id text,
  p_node_id text,
  p_epoch bigint,
  p_ttl_seconds integer default 60
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ttl integer := least(greatest(coalesce(p_ttl_seconds, 60), 30), 300);
  v_expires timestamptz := now() + make_interval(secs => v_ttl);
  v_rows integer := 0;
begin
  if auth.role() <> 'service_role' then raise exception 'service_role richiesta'; end if;
  update public.flbp_data_plane set
    lease_expires_at = v_expires, last_heartbeat_at = now(), updated_at = now()
  where workspace_id = p_workspace_id and mode = 'local'
    and node_id = p_node_id and epoch = p_epoch;
  get diagnostics v_rows = row_count;
  return jsonb_build_object('ok', true, 'accepted', v_rows = 1, 'epoch', p_epoch, 'lease_expires_at', v_expires);
end;
$$;

create or replace function public.flbp_local_backup_data_plane(
  p_workspace_id text,
  p_node_id text,
  p_epoch bigint,
  p_state jsonb,
  p_public_state jsonb,
  p_version bigint,
  p_operation_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plane record;
  v_cloud record;
  v_now timestamptz := now();
begin
  if auth.role() <> 'service_role' then raise exception 'service_role richiesta'; end if;
  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || p_workspace_id));
  select * into v_plane from public.flbp_data_plane
  where workspace_id = p_workspace_id for update;
  if not found or v_plane.mode not in ('local', 'recovery')
    or v_plane.node_id <> p_node_id or v_plane.epoch <> p_epoch
  then
    raise exception 'FLBP_EPOCH_FENCED: backup rifiutato, il nodo non possiede più questo epoch';
  end if;
  perform set_config(
    'flbp.local_backup_context',
    p_workspace_id || ':' || p_node_id || ':' || p_epoch::text,
    true
  );

  select version, last_operation_id into v_cloud
  from public.workspace_state
  where workspace_id = p_workspace_id
  for update;
  if found and coalesce(p_version, 0) < v_cloud.version then
    raise exception 'FLBP_DB_CONFLICT: backup locale versione % precedente alla versione cloud %', p_version, v_cloud.version;
  end if;
  if found and coalesce(p_version, 0) = v_cloud.version
    and coalesce(p_operation_id, '') <> coalesce(v_cloud.last_operation_id, '')
  then
    raise exception 'FLBP_DB_CONFLICT: la versione % è già associata a un’altra operazione', p_version;
  end if;

  insert into public.workspace_state (
    workspace_id, state, updated_at, version, last_operation_id, primary_epoch
  ) values (
    p_workspace_id, coalesce(p_state, '{}'::jsonb), v_now,
    greatest(coalesce(p_version, 1), 1), p_operation_id, p_epoch
  ) on conflict (workspace_id) do update set
    state = excluded.state,
    updated_at = excluded.updated_at,
    version = excluded.version,
    last_operation_id = excluded.last_operation_id,
    primary_epoch = excluded.primary_epoch;

  insert into public.public_workspace_state(workspace_id, state, updated_at)
  values (p_workspace_id, coalesce(p_public_state, '{}'::jsonb), v_now)
  on conflict (workspace_id) do update set state = excluded.state, updated_at = excluded.updated_at;

  insert into public.public_workspace_live(workspace_id, state, updated_at)
  values (p_workspace_id, coalesce(p_public_state, '{}'::jsonb), v_now)
  on conflict (workspace_id) do update set state = excluded.state, updated_at = excluded.updated_at;

  update public.flbp_data_plane set last_backup_at = v_now, updated_at = v_now
  where workspace_id = p_workspace_id and node_id = p_node_id and epoch = p_epoch;

  return jsonb_build_object('ok', true, 'updated_at', v_now, 'version', p_version, 'epoch', p_epoch);
end;
$$;

-- Backup finale e ritorno al cloud sono una singola transazione. In questo
-- modo una risposta HTTP persa può essere ritentata idempotentemente senza
-- lasciare un intervallo in cui il cloud è scrivibile ma il nodo locale crede
-- ancora di esserlo.
drop function if exists public.flbp_local_deactivate_data_plane(text, text, bigint);
create or replace function public.flbp_local_deactivate_data_plane(
  p_workspace_id text,
  p_node_id text,
  p_epoch bigint,
  p_state jsonb,
  p_public_state jsonb,
  p_version bigint,
  p_operation_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plane record;
  v_backup jsonb;
  v_now timestamptz := now();
begin
  if auth.role() <> 'service_role' then raise exception 'service_role richiesta'; end if;
  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || p_workspace_id));
  select * into v_plane
  from public.flbp_data_plane
  where workspace_id = p_workspace_id
  for update;
  if not found then
    raise exception 'FLBP_EPOCH_FENCED: coordinatore assente';
  end if;

  if v_plane.mode = 'cloud' and v_plane.epoch = p_epoch then
    return jsonb_build_object(
      'ok', true, 'deactivated', true, 'idempotent', true,
      'mode', 'cloud', 'epoch', p_epoch,
      'updated_at', coalesce(v_plane.last_backup_at, v_plane.updated_at),
      'version', p_version
    );
  end if;

  if v_plane.mode not in ('local', 'recovery')
    or v_plane.node_id <> p_node_id or v_plane.epoch <> p_epoch
  then
    raise exception 'FLBP_EPOCH_FENCED: disattivazione rifiutata, leadership cambiata';
  end if;

  v_backup := public.flbp_local_backup_data_plane(
    p_workspace_id, p_node_id, p_epoch,
    p_state, p_public_state, p_version, p_operation_id
  );

  update public.flbp_data_plane set
    mode = 'cloud', node_id = null, base_url = null,
    lease_expires_at = null, last_backup_at = v_now, updated_at = v_now
  where workspace_id = p_workspace_id and epoch = p_epoch;

  return jsonb_build_object(
    'ok', true, 'deactivated', true, 'idempotent', false,
    'mode', 'cloud', 'epoch', p_epoch,
    'updated_at', coalesce(v_backup->>'updated_at', v_now::text),
    'version', p_version
  );
end;
$$;

create or replace function public.flbp_resolve_data_plane(p_workspace_id text default 'default')
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_plane record;
begin
  select * into v_plane from public.flbp_data_plane where workspace_id = p_workspace_id;
  if not found or v_plane.mode = 'cloud' then
    return jsonb_build_object('mode', 'cloud', 'epoch', coalesce(v_plane.epoch, 0));
  end if;
  if v_plane.mode = 'local' and v_plane.lease_expires_at > now() then
    return jsonb_build_object(
      'mode', 'local', 'base_url', v_plane.base_url, 'epoch', v_plane.epoch,
      'lease_expires_at', v_plane.lease_expires_at
    );
  end if;
  return jsonb_build_object(
    'mode', 'recovery', 'epoch', v_plane.epoch,
    'reason', 'local_lease_expired', 'last_backup_at', v_plane.last_backup_at
  );
end;
$$;

-- Failover distruttivo solo esplicito: viene usato esclusivamente quando il
-- PC locale non è recuperabile e la lease è già scaduta. L'epoch avanza per
-- impedire a quel processo, se riappare, di pubblicare operazioni vecchie.
create or replace function public.flbp_admin_force_cloud_failover(
  p_workspace_id text default 'default',
  p_expected_epoch bigint default 0,
  p_confirmation text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_workspace_id text := coalesce(nullif(trim(p_workspace_id), ''), 'default');
  v_plane record;
  v_new_epoch bigint;
  v_cloud_version bigint := 0;
  v_journal_version bigint := 0;
begin
  if not public.flbp_is_admin() then raise exception 'Accesso admin richiesto'; end if;
  if p_confirmation <> 'FAILOVER CLOUD CON POSSIBILE PERDITA' then
    raise exception 'Conferma failover non valida';
  end if;

  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || v_workspace_id));
  select * into v_plane
  from public.flbp_data_plane
  where workspace_id = v_workspace_id
  for update;
  if not found then
    return jsonb_build_object('ok', true, 'mode', 'cloud', 'epoch', 0, 'idempotent', true);
  end if;
  if v_plane.mode = 'cloud' and v_plane.epoch = p_expected_epoch + 1 then
    return jsonb_build_object(
      'ok', true, 'mode', 'cloud', 'epoch', v_plane.epoch,
      'idempotent', true, 'last_backup_at', v_plane.last_backup_at
    );
  end if;
  if v_plane.epoch <> p_expected_epoch then
    raise exception 'FLBP_EPOCH_FENCED: epoch cambiato; aggiorna lo stato prima del failover';
  end if;
  if v_plane.mode = 'local' and v_plane.lease_expires_at > now() then
    raise exception 'FLBP_LOCAL_PRIMARY: il PC locale risulta ancora attivo; usa la disattivazione normale';
  end if;

  select coalesce(max(version), 0) into v_cloud_version
  from public.workspace_state
  where workspace_id = v_workspace_id;
  select coalesce(max(local_version), v_cloud_version) into v_journal_version
  from public.flbp_local_operation_log
  where workspace_id = v_workspace_id and primary_epoch = v_plane.epoch;
  if v_journal_version > v_cloud_version then
    raise exception 'FLBP_RECOVERY_JOURNAL_PENDING: il journal remoto arriva alla versione %, lo snapshot cloud solo alla %; usa un server sostitutivo per riprodurlo prima del failover', v_journal_version, v_cloud_version;
  end if;

  v_new_epoch := v_plane.epoch + 1;
  update public.flbp_data_plane set
    mode = 'cloud', node_id = null, base_url = null,
    epoch = v_new_epoch, lease_expires_at = null, updated_at = now()
  where workspace_id = v_workspace_id;

  return jsonb_build_object(
    'ok', true, 'mode', 'cloud', 'epoch', v_new_epoch,
    'idempotent', false, 'last_backup_at', v_plane.last_backup_at,
    'warning', 'Le operazioni rimaste solo sul PC locale non sono incluse.'
  );
end;
$$;

