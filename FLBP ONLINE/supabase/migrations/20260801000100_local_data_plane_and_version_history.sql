-- FLBP Manager Suite - local tournament data plane + durable version history.
--
-- Invariants:
-- 1. exactly one writable data plane per workspace (cloud or local epoch);
-- 2. an expired local leader enters recovery, never automatic writable cloud;
-- 3. every workspace snapshot change is versioned and recoverable;
-- 4. local operations are idempotent and mirrored as an append-only outbox;
-- 5. service_role is the only identity allowed to coordinate/backup a local node.

alter table public.workspace_state
  add column if not exists version bigint not null default 1,
  add column if not exists last_operation_id text,
  add column if not exists primary_epoch bigint;

create table if not exists public.workspace_state_versions (
  id bigint generated by default as identity primary key,
  workspace_id text not null references public.workspaces(id) on delete cascade,
  version bigint not null,
  operation_id text,
  primary_epoch bigint,
  state jsonb not null,
  state_bytes bigint not null default 0,
  checksum text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  unique (workspace_id, version)
);

alter table public.workspace_state_versions enable row level security;
revoke all on table public.workspace_state_versions from public, anon, authenticated;

create or replace function public.flbp_workspace_state_before_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text := coalesce(auth.role(), '');
  v_plane record;
  v_backup_context text := coalesce(current_setting('flbp.local_backup_context', true), '');
  v_workspace_id text;
begin
  v_workspace_id := case when tg_op = 'DELETE' then old.workspace_id else new.workspace_id end;
  -- Serializza ogni write cloud con activate/deactivate del data plane. Una
  -- transazione iniziata durante lo switch attende il lock e poi vede il
  -- nuovo mode, invece di attraversare la finestra tra pull e leadership.
  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || v_workspace_id));
  select mode, node_id, epoch, lease_expires_at
  into v_plane
  from public.flbp_data_plane
  where workspace_id = v_workspace_id;

  if found and v_plane.mode in ('local', 'recovery') then
    -- La service role da sola non è un lasciapassare: solo la RPC di backup
    -- che ha verificato node_id + epoch imposta questo contesto transazionale.
    if v_role <> 'service_role'
      or v_backup_context <> (v_workspace_id || ':' || v_plane.node_id || ':' || v_plane.epoch::text)
    then
      if v_plane.mode = 'local' and v_plane.lease_expires_at > now() then
      raise exception 'FLBP_LOCAL_PRIMARY: il server locale è il nodo di scrittura attivo'
        using detail = jsonb_build_object(
          'node_id', v_plane.node_id,
          'epoch', v_plane.epoch,
          'lease_expires_at', v_plane.lease_expires_at
        )::text;
      else
      raise exception 'FLBP_DATA_PLANE_RECOVERY: leadership locale scaduta; le scritture restano sospese fino al recupero esplicito'
        using detail = jsonb_build_object('epoch', v_plane.epoch)::text;
      end if;
    end if;
  end if;

  if tg_op = 'UPDATE' and new.state is distinct from old.state then
    if new.version is null or new.version <= old.version then
      new.version := old.version + 1;
    end if;
    if nullif(trim(coalesce(new.last_operation_id, '')), '') is null
      or new.last_operation_id = old.last_operation_id
    then
      new.last_operation_id := 'legacy-' || md5(clock_timestamp()::text || random()::text);
    end if;
  elsif tg_op = 'INSERT' then
    new.version := greatest(coalesce(new.version, 1), 1);
    if nullif(trim(coalesce(new.last_operation_id, '')), '') is null then
      new.last_operation_id := 'initial-' || md5(clock_timestamp()::text || random()::text);
    end if;
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

