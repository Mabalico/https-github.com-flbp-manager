create or replace function public.flbp_local_operation_log_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plane record;
begin
  if auth.role() <> 'service_role' then raise exception 'service_role richiesta'; end if;
  if new.primary_epoch is null then raise exception 'primary_epoch mancante'; end if;

  if tg_op = 'UPDATE' and (
    new.workspace_id is distinct from old.workspace_id
    or new.node_id is distinct from old.node_id
    or new.primary_epoch is distinct from old.primary_epoch
    or new.operation_id is distinct from old.operation_id
    or new.local_version is distinct from old.local_version
    or new.operation_kind is distinct from old.operation_kind
    or new.payload is distinct from old.payload
    or new.created_at is distinct from old.created_at
  ) then
    raise exception 'FLBP_APPEND_ONLY: i dati di una operazione journal non sono modificabili';
  end if;

  -- Usa lo stesso lock dello switch. Un upload partito prima di activate viene
  -- completato e incluso nel controllo high-water; uno partito dopo attende e
  -- viene respinto perché l'epoch è ormai cambiato.
  perform pg_advisory_xact_lock(hashtext('flbp_data_plane:' || new.workspace_id));
  select mode, node_id, epoch into v_plane
  from public.flbp_data_plane
  where workspace_id = new.workspace_id;
  if not found or v_plane.mode <> 'local'
    or v_plane.node_id <> new.node_id or v_plane.epoch <> new.primary_epoch
  then
    raise exception 'FLBP_EPOCH_FENCED: operazione journal rifiutata';
  end if;
  return new;
end;
$$;

